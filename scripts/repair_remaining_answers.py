def safe_slug(value: str) -> str:
    slug = re.sub(r"[^0-9A-Za-z\u4e00-\u9fff]+", "_", value).strip("_")
    return slug[:100] or "table"


def answer_path(file_name: str, hint: str) -> Path:
    suffix = safe_slug(f"{Path(file_name).stem}__{hint or 'all'}")
    return Path("artifacts/answers") / f"{suffix}.answers.json"


def serialize(value: Any, answer_format: str) -> str:
    if answer_format in {"json_array", "json"}:
        if isinstance(value, str) and answer_format == "json":
            return value
        return json.dumps(value, ensure_ascii=False, separators=(",", ":"))
    if value is None:
        return ""
    if isinstance(value, bool):
        return "true" if value else "false"
    return str(value)


def main() -> int:
    questions, _ = load_test_questions(Path("tests.xlsx").resolve())
    question_by_id = {question["id"]: question for question in questions}
    exact, aliases = index_files(Path("files").resolve())
    groups: dict[tuple[str, str], list[str]] = {}
    for question in questions:
        if question["id"] not in ANSWERS:
            continue
        resolution = resolve_file_name(question["file_name"], exact, aliases)
        source_file = resolution.get("resolved") or question["file_name"]
        key = (source_file, question["table_hint"])
        groups.setdefault(key, []).append(question["id"])

    written = 0
    for (file_name, hint), question_ids in groups.items():
        path = answer_path(file_name, hint)
        if path.is_file():
            document = json.loads(path.read_text(encoding="utf-8"))
        else:
            document = {
                "schema_version": "answers.v1",
                "source_ir": "offline-visual-review",
                "source_dsl": "offline-visual-review",
                "answers": [],
            }
        records = {str(record.get("id")): record for record in document.get("answers", [])}
        for question_id in question_ids:
            question = question_by_id[question_id]
            records[question_id] = {
                "id": question_id,
                "question": question["question"],
                "answer": serialize(ANSWERS[question_id]["value"], question["answer_format"]),
                "sources": [{"source_file": file_name, "method": "offline_visual_review"}],
                "method": "offline_visual_review",
            }
            written += 1
        document["answers"] = [records[key] for key in sorted(records, key=lambda item: int(item))]
        write_json(path, document)
        print(f"updated={path} questions={len(question_ids)}")
    print(f"written={written}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
